package com.foodmemory.app.auth.oauth;

import com.foodmemory.app.entity.Provider;

/**
 * 소셜 로그인 제공자 하나와 이야기하는 방법.
 *
 * 카카오와 구글은 주소도 다르고 응답 모양도 다르지만, 하는 일의 순서는 똑같다.
 *
 *   1. 사용자를 제공자의 로그인 화면으로 보낸다              → authorizeUrl()
 *   2. 사용자가 동의하면 제공자가 '인가 코드'를 들고 우리에게 돌아온다
 *   3. 그 코드를 토큰으로 바꾸고, 토큰으로 사용자 정보를 받아온다  → fetchUserInfo()
 *
 * 여기서 인가 코드를 한 번 거치는 이유:
 *   토큰을 곧바로 브라우저에 주면 주소창과 브라우저 기록에 남는다.
 *   인가 코드는 한 번만 쓸 수 있고 수명이 짧으며, 토큰으로 바꾸는 일은
 *   서버끼리 직접 통신하면서 이루어진다. 토큰이 브라우저를 거치지 않는다.
 *
 * 이 순서를 인터페이스로 고정해두면 제공자를 추가할 때 구현체만 하나 더 만들면 된다.
 * 컨트롤러와 서비스는 손대지 않는다.
 */
public interface OAuthClient {

    /** 이 클라이언트가 담당하는 제공자. 어느 구현체를 쓸지 고르는 기준이 된다. */
    Provider provider();

    /** 설정이 채워져 있는지. 키가 없으면 로그인 시도 자체를 막고 안내한다. */
    boolean isConfigured();

    /**
     * 사용자를 보낼 제공자의 로그인·동의 화면 주소.
     *
     * @param state 위조 요청을 막기 위한 임의의 문자열. 돌아올 때 같은 값인지 확인한다
     */
    String authorizeUrl(String state);

    /**
     * 인가 코드를 사용자 정보로 바꾼다. 토큰 교환과 사용자 조회를 함께 처리한다.
     *
     * 두 단계를 나누지 않은 이유:
     *   토큰은 사용자 정보를 얻기 위한 중간 재료일 뿐이고, 우리는 토큰을 저장하지 않는다.
     *   (카카오톡 메시지 보내기 같은 기능을 붙일 때가 되면 그때 나눈다)
     *   밖으로 드러내면 쓰는 쪽이 토큰을 어딘가 보관하고 싶어진다.
     */
    OAuthUserInfo fetchUserInfo(String code);
}
