-- ============================================================
--  post 에서 is_public 을 지운다
--  2026-09-20
-- ============================================================
--
-- ── 무엇을 하나 ──
--
-- 공개 여부를 담으려고 만든 칸인데, 한 번도 읽히지 않았다.
-- 실제로 공개 범위를 정하는 것은 space_id 다. 비어 있으면 개인 기록,
-- 채워져 있으면 그 공간의 참여자가 본다. is_public 은 그 판단에 끼어든 적이 없다.
--
-- 쓰이지 않는 칸을 남겨두면, 나중에 보는 사람이 이 값을 믿고 코드를 짠다.
-- 값은 전부 기본값(0)이라 그 코드는 조용히 틀린다.
--
-- ── 순서가 중요하다 ──
--
-- 이 SQL 은 배포 '뒤에' 돌린다. photo-location 때와 반대다.
--
--   칸을 더할 때는 DB 가 먼저다. 앱이 먼저 뜨면 없는 칸을 찾다가 죽는다.
--   칸을 지울 때는 앱이 먼저다. DB 가 먼저 지워지면, 아직 그 칸을 아는
--   옛 앱이 못 뜬다. (ddl-auto: validate 는 '없는 칸'만 문제 삼는다)
--
-- 그래서 배포한 뒤 앱이 정상인 것을 보고 나서 돌린다. 급하지 않다.
-- 남아 있어도 앱은 잘 돈다. 그저 쓰이지 않는 칸일 뿐이다.
--
-- ── 되돌릴 수 있나 ──
--
-- 칼럼을 지우면 그 안의 값도 함께 사라진다. 이 칸은 전부 기본값(0)이라
-- 잃을 값이 없지만, 되살리려면 아래를 돌린다.
--
--   ALTER TABLE post ADD COLUMN is_public BOOLEAN NOT NULL DEFAULT FALSE COMMENT '공개 여부' AFTER eaten_date;
--
--   운영:  ssh 로 들어가  sudo mysql foodmemory < 이 파일
--   로컬:  mysql -u root -p foodmemory < 이 파일

ALTER TABLE post
    DROP COLUMN is_public;
