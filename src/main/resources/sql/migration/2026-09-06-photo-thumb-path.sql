-- ============================================================
--  photo 에 thumb_path 를 추가한다
--  2026-09-06
-- ============================================================
--
-- ── 왜 이 파일이 따로 있나 ──
--
-- schema.sql 은 맨 앞에서 테이블을 전부 DROP 하고 새로 만든다.
-- 처음 자리를 잡을 때는 그게 편하지만, 이미 사람들의 기록이 들어 있는 DB 에
-- 그걸 돌리면 전부 사라진다. 그래서 이미 도는 DB 에는 '달라진 것만' 따로 붙인다.
--
-- ── 무엇을 하나 ──
--
-- 목록 화면이 2.5MB 짜리 원본을 그대로 내려보내던 것을, 작은 사본을 만들어
-- 그것만 보내도록 바꾼다. 그 사본의 경로를 담을 칸이다.
--
-- ── 안전한가 ──
--
-- NULL 을 허용하는 칸을 뒤에 붙이는 것이라 기존 행은 건드리지 않는다.
-- MySQL 8.0 은 이런 추가를 테이블을 잠그지 않고 처리하므로(INSTANT),
-- 사이트를 멈추지 않아도 된다. 사진이 11장뿐인 지금은 어차피 순식간이다.
--
-- ── 순서가 중요하다 ──
--
-- 이 SQL 을 '먼저' 돌리고 배포한다.
-- 앱은 ddl-auto: validate 라 엔티티와 테이블이 다르면 아예 뜨지 않는다.
-- 배포를 먼저 하면 앱이 못 떠서 사이트가 멈춘다.
--
--   운영:  ssh 로 들어가  sudo mysql foodmemory < 이 파일
--   로컬:  mysql -u root -p foodmemory < 이 파일

ALTER TABLE photo
    ADD COLUMN thumb_path VARCHAR(500) NULL
    COMMENT '썸네일 경로 (없으면 원본을 쓴다)'
    AFTER file_path;
